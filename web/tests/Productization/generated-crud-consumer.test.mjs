function script(file) {
  const text = read(path.join(outputRoot, file));
  if (!file.endsWith('.vue')) return text;
  const result = sfc.parse(text, { filename: file });
  assert.deepEqual(result.errors, []);
  assert.equal(result.descriptor.script, null);
  assert.equal(result.descriptor.scriptSetup?.lang, 'ts');
  return result.descriptor.scriptSetup.content;
}
function imports(file) {
  const tree = ts.createSourceFile(
    file,
    script(file),
    ts.ScriptTarget.Latest,
    true
  );
  const results = [];
  function visit(node) {
    if (
      (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) &&
      node.moduleSpecifier
    ) {
      assert.ok(ts.isStringLiteral(node.moduleSpecifier));
      results.push(node.moduleSpecifier.text);
    }
    if (
      ts.isCallExpression(node) &&
      node.expression.kind === ts.SyntaxKind.ImportKeyword
    ) {
      assert.equal(node.arguments.length, 1);
      assert.ok(
        ts.isStringLiteral(node.arguments[0]),
        'Unregistered dynamic generated import'
      );
      results.push(node.arguments[0].text);
    }
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return results;
}
function resolveLocal(file, specifier) {
  const base = specifier.startsWith('@/')
    ? `web/src/${specifier.slice(2)}`
    : path.posix.normalize(
        path.posix.join(path.posix.dirname(file), specifier)
      );
  assert.ok(base.startsWith('web/src/') && !base.split('/').includes('..'));
  for (const suffix of ['', '.ts', '.vue', '/index.ts']) {
    const relative = base + suffix;
    if (outputs.has(relative))
      return exactFile(path.join(outputRoot, relative));
    const host = path.join(root, relative);
    if (existsSync(host) && statSync(host).isFile()) return exactFile(host);
  }
  assert.fail(`Missing generated consumer import: ${file} -> ${specifier}`);
}

