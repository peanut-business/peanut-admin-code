const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const read = (file) => readFileSync(file, 'utf8');
const git = (...args) =>
  execFileSync('git', args, { cwd: root, encoding: 'utf8' });
function commitInput(name) {
  const value = process.env[name];
  assert.match(
    value ?? '',
    /^[a-f0-9]{40}$/,
    `${name} must be an exact commit`
  );
  git('cat-file', '-e', `${value}^{commit}`);
  return value;
}
function within(parent, child) {
  const relative = path.relative(parent, child);
  return (
    relative !== '' &&
    relative !== '..' &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}
function ownedExisting(value, directory) {
  assert.ok(value, `A ${directory} path is required`);
  const result = realpathSync(path.resolve(root, value));
  assert.ok(
    within(path.join(root, '.local', directory), result),
    'Input must belong to this checkout'
  );
  return result;
}
function sourcePath(relative) {
  assert.match(
    relative,
    /^web\/src\/modules\/[a-z0-9-]+\/(?:[a-z0-9-]+\/)*(?:[a-z0-9-]+\.ts|index\.vue)$/
  );
  return relative;
}
function exactFile(file) {
  assert.ok(
    existsSync(file) && statSync(file).isFile(),
    `Missing consumer source: ${file}`
  );
  const parsed = path.parse(file);
  let directory = parsed.root;
  for (const part of file.slice(parsed.root.length).split(path.sep)) {
    assert.ok(
      readdirSync(directory).includes(part),
      `Incorrect path case: ${file}`
    );
    directory = path.join(directory, part);
  }
  return file;
}
