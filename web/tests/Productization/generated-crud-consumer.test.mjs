test('generated static/dynamic imports resolve to declared production dependencies and exact files', () => {
  const missing = [];
  let count = 0;
  for (const file of outputs.keys()) {
    for (const specifier of imports(file)) {
      count++;
      if (specifier.startsWith('.') || specifier.startsWith('@/')) {
        resolveLocal(file, specifier);
        continue;
      }
      const parts = specifier.split('/');
      const packageName = specifier.startsWith('@')
        ? parts.slice(0, 2).join('/')
        : parts[0];
      if (!Object.hasOwn(packageJson.dependencies, packageName)) {
        missing.push(`${file}: ${specifier}`);
        continue;
      }
      // The frontend consumes ESM exports; require.resolve would incorrectly
      // reject packages that intentionally expose only an import condition.
      if (!Object.hasOwn(corePaths, packageName))
        exactFile(fileURLToPath(import.meta.resolve(specifier)));
    }
  }
  report.checks.imports = { passed: missing.length === 0, count, missing };
  assert.deepEqual(
    missing,
    [],
    'Generated imports must use the actual target frontend dependencies'
  );
});

test('actual generated template components exist in the installed and registered UI', () => {
  const main = read(path.join(webRoot, 'src/main.ts'));
  assert.match(main, /import ElementPlus from 'element-plus'/);
  assert.match(main, /app\.use\(ElementPlus\)/);
  const ui = native('element-plus');
  const missing = [];
  const tags = [];
  for (const file of views) {
    const { descriptor } = sfc.parse(read(path.join(outputRoot, file)), {
      filename: file,
    });
    const compiledScript = sfc.compileScript(descriptor, {
      id: 'crud-consumer',
    });
    const template = sfc.compileTemplate({
      source: descriptor.template.content,
      filename: file,
      id: 'crud-consumer',
    });
    assert.deepEqual(template.errors, []);
    function visit(node) {
      if (node.type === 1 && node.tagType === 1) {
        const name = node.tag.replace(/(^|-)([a-z])/g, (_all, _dash, letter) =>
          letter.toUpperCase()
        );
        const imported =
          compiledScript.imports[node.tag] ?? compiledScript.imports[name];
        const explicit = imported && !imported.isType;
        tags.push(node.tag);
        if (
          !explicit &&
          !Object.hasOwn(ui, name) &&
          ![
            'Transition',
            'TransitionGroup',
            'KeepAlive',
            'Teleport',
            'Suspense',
          ].includes(name)
        )
          missing.push(`${file}: ${node.tag}`);
      }
      for (const child of node.children ?? []) visit(child);
    }
    visit(template.ast);
  }
  report.checks.components = { passed: missing.length === 0, tags, missing };
  assert.deepEqual(
    missing,
    [],
    'Unregistered components cannot become passing HTML custom elements'
  );
});

test('real generated Vue/API files pass native strict vue-tsc with actual component declarations', () => {
  const files = [...outputs.keys()]
    .filter((file) => file.endsWith('/index.vue') || file.endsWith('/api.ts'))
    .map((file) => path.join(work, file));
  const globalTypes = exactFile(
    path.join(webRoot, 'node_modules/element-plus/global.d.ts')
  );
  const configuration = {
    extends: path.join(webRoot, 'tsconfig.json'),
    compilerOptions: {
      paths: { '@/*': [path.join(webRoot, 'src/*')], ...corePaths },
    },
    vueCompilerOptions: { strictTemplates: true },
    files: [...files, path.join(webRoot, 'src/env.d.ts'), globalTypes],
    include: [],
    exclude: [],
  };
  const config = path.join(replayWeb, 'tsconfig.json');
  writeFileSync(config, JSON.stringify(configuration, null, 2) + '\n');
  const result = spawnSync(
    process.execPath,
    [native.resolve('vue-tsc/bin/vue-tsc.js'), '--noEmit', '--project', config],
    { cwd: replayWeb, encoding: 'utf8', timeout: 90000 }
  );
  writeFileSync(
    path.join(reportDirectory, 'vue-tsc.log'),
    (result.stdout ?? '') + (result.stderr ?? '')
  );
  report.checks.types = {
    passed: result.status === 0 && !result.error,
    exitCode: result.status,
    signal: result.signal,
    files,
    config,
  };
  assert.equal(result.error, undefined);
  assert.equal(result.status, 0, (result.stdout ?? '') + (result.stderr ?? ''));
});

test('the unchanged generated SFCs compile through native Vite/Vue without externalizing missing packages', async () => {
  const { build } = native('vite');
  const vuePlugin = native('@vitejs/plugin-vue');
  const logs = [];
  try {
    for (const [index, file] of views.entries()) {
      await build({
        configFile: false,
        root: replayWeb,
        publicDir: false,
        logLevel: 'error',
        plugins: [vuePlugin()],
        resolve: {
          alias: [
            { find: '@', replacement: path.join(webRoot, 'src') },
            ...runtimeAliases,
          ],
          dedupe: ['vue', 'pinia', 'element-plus'],
        },
        build: {
          lib: {
            entry: path.join(work, file),
            formats: ['es'],
            fileName: () => `crud-${index}.mjs`,
          },
          outDir: path.join(work, `dist-${index}`),
          emptyOutDir: false,
          minify: false,
        },
      });
      logs.push({ file, compiled: true });
    }
    report.checks.bundle = { passed: true, files: logs };
  } catch (error) {
    report.checks.bundle = { passed: false, files: logs, error: String(error) };
    throw error;
  }
});
