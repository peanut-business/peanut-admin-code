// PEANUT_GENERATOR_COMMIT / PEANUT_FRONTEND_COMMIT: exact local Git objects.
// Optional PEANUT_CRUD_CORE_ROOT / PEANUT_CRUD_CORE_COMMIT selects compiled
// public Core entries; omission tests the target web application's native lock.
// Run: node --test web/tests/Productization/generated-crud-consumer.test.mjs
// Generated bytes are never patched. Failure workspaces and reports are retained.
const root = realpathSync(fileURLToPath(new URL('../../..', import.meta.url)));
const webRoot = path.join(root, 'web');
